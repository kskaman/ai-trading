"""
Generate docs/configuration.md from the settings classes in src/config/settings.py.

    python -m scripts.gen_config_docs          # rewrite the page
    python -m scripts.gen_config_docs --check  # exit 1 if the page is out of date

tests/test_docs.py runs the check, so the page cannot drift from the code.
Run from the project root.
"""

import argparse
import sys
from pathlib import Path
from typing import List, Type

from pydantic import AliasChoices
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined
from pydantic_settings import BaseSettings

from src.config.settings import (
    DataSettings, ExecutionSettings, ModelSettings, RiskSettings, TradingSettings,
)

OUTPUT = Path(__file__).resolve().parents[1] / 'docs' / 'configuration.md'

SECTIONS = [
    (DataSettings, 'Data',
     'Market data sources, storage, retries, CCXT and the real-time feed. '
     'Used by everything under `src/market_data`.'),
    (ExecutionSettings, 'Execution',
     'Broker credentials and the paper/live switch. Used by `src/execution`.'),
    (TradingSettings, 'Trading profile',
     'Which profile is running. Checked by `TradingSettings.validate_startup()`.'),
    (RiskSettings, 'Risk',
     'Position and loss limits, trading costs. Not used by any code yet.'),
    (ModelSettings, 'Model',
     'Walk-forward training and model hyperparameters. Not used by any code yet.'),
]

HEADER = """\
# Configuration

<!-- Generated by `python -m scripts.gen_config_docs` from src/config/settings.py.
     Do not edit by hand: change the Field descriptions in settings.py instead. -->

All settings come from **environment variables** or a **`.env` file** in the
directory you run from (the project root). Real environment variables win over
`.env`; names are case-insensitive. Nothing is configured in code.

```ini
# .env (never commit this file; .env.example is the template)
ALPACA_API_KEY=your_api_key
ALPACA_API_SECRET=your_api_secret
ALPACA_PAPER=true
DATA_CCXT_EXCHANGE_ID=kraken
DATA_MAX_RETRY_ATTEMPTS=5
```

In code, read settings with `get_settings()` (cached) and call
`reset_settings()` to reload them. Every component also accepts a settings
object directly, which is how the tests configure them.

Values marked *secret* are stored as `SecretStr`: they never appear in logs or
`repr()`; read them with `.get_secret_value()`.
"""


def _env_names(model: Type[BaseSettings], name: str, field: FieldInfo) -> List[str]:
    alias = field.validation_alias
    if isinstance(alias, AliasChoices):
        return [c for c in alias.choices if isinstance(c, str)]
    if isinstance(alias, str):
        return [alias]
    return [(model.model_config.get('env_prefix', '') + name).upper()]


def _default(field: FieldInfo) -> str:
    value = field.default
    if value is None or value is PydanticUndefined:
        return '-'
    if isinstance(value, bool):
        return f'`{str(value).lower()}`'
    return f'`{value}`'


def _description(field: FieldInfo) -> str:
    text = (field.description or '').replace('|', '\\|')
    if 'SecretStr' in str(field.annotation):
        text += ' *(secret)*'
    return text


def _is_nested_settings(field: FieldInfo) -> bool:
    return isinstance(field.annotation, type) and issubclass(field.annotation, BaseSettings)


def render() -> str:
    parts = [HEADER]
    for model, title, summary in SECTIONS:
        parts.append(f'\n## {title}\n\n{summary}\n\n')
        parts.append('| Variable | Default | Description |\n|---|---|---|\n')
        for name, field in model.model_fields.items():
            if _is_nested_settings(field):
                continue
            names = ' or '.join(f'`{n}`' for n in _env_names(model, name, field))
            parts.append(f'| {names} | {_default(field)} | {_description(field)} |\n')
    return ''.join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail if the page is stale')
    args = parser.parse_args()

    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current != content:
            print(f'{OUTPUT} is out of date; run: python -m scripts.gen_config_docs')
            return 1
        print(f'{OUTPUT} is up to date')
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print(f'Wrote {OUTPUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
